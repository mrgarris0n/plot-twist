// The Hungarian wording, same shape as `english`. Plant and bed names arrive uninflected and stay that way:
// sentences put them before a colon or dash, or use them as the subject. `article()` picks a/az.
import { article } from './article.js'
import { formatNumber, localizeDecimal } from './lang.js'
import { english, type LightObstacle, type Strings } from './english.js'

type W = Strings['warnings']
type SunNeedWord = Parameters<W['lightNow']>[1]
type AcidityClass = Parameters<W['soilAcidity']>[1]
type TextureWord = Parameters<W['soilTexture']>[1]
type DrainageWord = Parameters<W['soilDrainage']>[1]

const NEED: Record<SunNeedWord, string> = { full: 'napos helyre (napi 6+ óra)', part: 'félárnyékra (napi 3+ óra)', shade: 'egy kis árnyékra' }
const ACIDITY: Record<AcidityClass, string> = { acidic: 'savanyú', neutral: 'semleges', alkaline: 'lúgos' }
const TEXTURE: Record<TextureWord, string> = { sandy: 'homokos', loamy: 'vályogos', clay: 'agyagos', silty: 'iszapos' }
const DRAINAGE: Record<DrainageWord, string> = { fast: 'gyorsan átengedi a vizet', normal: 'átlagosan vezeti el a vizet', wet: 'sokáig nedves marad' }
const ROTATION_GROUP: Strings['rotation']['group'] = {
  potatoes: 'Burgonya és paradicsom',
  legumes: 'Borsó és bab',
  brassicas: 'Káposztafélék',
  roots: 'Hagymák és gyökérzöldségek',
  any: 'Bárhová jó',
}

const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1)
/** "a dió", "az eperfa": an article and the name, lower-cased as in the English. */
const the = (name: string) => `${article(name)} ${name.toLowerCase()}`
/** An ordinal year with its article: "a 3. év", "az 5. év". */
const hu = (n: number) => localizeDecimal(String(n), 'hu')
const theYear = (n: number) => `${article(String(n))} ${n}.`
const theObstacle = (o: LightObstacle) => the(o.name)

/** Same plant twice → "Két alma"; else "Alma és fekete ribiszke". */
function pair(a: string, b: string): string {
  return a === b ? `Két ${a.toLowerCase()}` : `${a} és ${b.toLowerCase()}`
}

